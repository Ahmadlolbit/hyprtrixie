register_module 12 "Desktop session"

option DISPLAY_SCALE --section input --label "Display scale" --type choice \
  --default auto --values "auto 1 1.25 1.5 1.75 2"
option NATURAL_SCROLL --section input --label "Natural scrolling" --type bool --default no
option TAP_TO_CLICK --section input --label "Tap to click" --type bool --default yes
option ANIMATIONS --section look --label "Animations" --type bool --default yes
option WINDOW_STYLE --section look --label "Window style" --type choice \
  --default sharp --values "sharp soft"
option IDLE_LOCK_MINUTES --section system --label "Lock the screen after idle minutes (0 = never)" --type number --default 5
option IDLE_SUSPEND_MINUTES --section system --label "Suspend after idle minutes (0 = never)" --type number --default 30

HYPR_SHARE="$SHARE_DIR/hypr"
ELEPHANT_LIB=/usr/local/lib/elephant
ELEPHANT_PROVIDERS=(desktopapplications calc runner files symbols websearch clipboard providerlist unicode menus)

lua_bool() {
  if [[ $1 == yes ]]; then
    printf 'true'
  else
    printf 'false'
  fi
}

lua_scale() {
  if [[ $1 == auto ]]; then
    printf '"auto"'
  else
    printf '%s' "$1"
  fi
}

hyprland_defaults() {
  deploy_tree "$HYPRTRIXIE_ROOT/config/hypr" "$HYPR_SHARE" || return 1
  deploy_file "$HYPRTRIXIE_ROOT/system/hypr/hyprland.lua" /etc/xdg/hypr/hyprland.lua
}

hyprland_options() {
  deploy_rendered "$HYPRTRIXIE_ROOT/system/hypr/options.lua" /etc/hyprtrixie/hypr/options.lua 0644 root \
    "NATURAL_SCROLL=$(lua_bool "$NATURAL_SCROLL")" "TAP_TO_CLICK=$(lua_bool "$TAP_TO_CLICK")" \
    "ANIMATIONS=$(lua_bool "$ANIMATIONS")" "SCALE=$(lua_scale "$DISPLAY_SCALE")" "WINDOW_STYLE=$WINDOW_STYLE"
}

hyprland_user_config() {
  local file
  file="$(user_path .config/hypr/hyprland.lua)"
  if [[ -f $file ]] && grep -q 'autogenerated = true' "$file"; then
    mv -f "$file" "$file.hyprtrixie-old" || return 1
  fi
  deploy_user_once "$HYPRTRIXIE_ROOT/system/hypr/hyprland.lua" .config/hypr/hyprland.lua
}

hyprland_user_ready() {
  grep -qF "$HYPR_SHARE/hyprtrixie.lua" "$(user_path .config/hypr/hyprland.lua)" 2>/dev/null
}

hyprland_config_ok() {
  local runtime out
  runtime="$(mktemp -d)" || return 1
  chown "$TARGET_USER:" "$runtime" || return 1
  out="$(as_user env XDG_RUNTIME_DIR="$runtime" Hyprland --verify-config 2>&1)"
  rm -rf "$runtime"
  if [[ "$(awk '/Config parsing result:/ { found = 1; next } found && NF { print; exit }' <<<"$out")" == "config ok" ]]; then
    return 0
  fi
  sed -n '/Config parsing result:/,$p' <<<"$out" | head -n 20
  return 1
}

hyprlock_setup() {
  local clock="\$TIME"
  if [[ $CLOCK_FORMAT == 12h ]]; then
    clock="\$TIME12"
  fi
  deploy_rendered "$HYPRTRIXIE_ROOT/system/hypr/hyprlock.conf" /etc/xdg/hypr/hyprlock.conf 0644 root "TIME=$clock"
}

idle_listener() {
  printf '\nlistener {\n    timeout = %s\n    on-timeout = %s\n' "$1" "$2"
  if [[ -n ${3:-} ]]; then
    printf '    on-resume = %s\n' "$3"
  fi
  printf '}\n'
}

hypridle_config() {
  local lock=$((IDLE_LOCK_MINUTES * 60)) suspend=$((IDLE_SUSPEND_MINUTES * 60))
  local on="hyprctl dispatch 'hl.dsp.dpms({action = \"on\"})'" off="hyprctl dispatch 'hl.dsp.dpms({action = \"off\"})'"
  printf 'general {\n    lock_cmd = pidof hyprlock || hyprlock\n    before_sleep_cmd = loginctl lock-session\n'
  printf '    after_sleep_cmd = %s\n}\n' "$on"
  if ((lock > 0)); then
    if ((lock > 60)); then
      idle_listener $((lock - 30)) "brightnessctl -s set 10%" "brightnessctl -r"
      idle_listener $((lock - 30)) "brightnessctl -sd '*::kbd_backlight' set 0" "brightnessctl -rd '*::kbd_backlight'"
    fi
    idle_listener "$lock" "loginctl lock-session"
    idle_listener $((lock + 30)) "$off" "$on"
  fi
  if ((suspend > 0)); then
    idle_listener "$suspend" "systemctl suspend"
  fi
}

hypridle_setup() {
  local tmp rc
  tmp="$(mktemp)" || return 1
  hypridle_config >"$tmp" && deploy_file "$tmp" /etc/xdg/hypr/hypridle.conf
  rc=$?
  rm -f "$tmp"
  return "$rc"
}

hyprpaper_setup() {
  deploy_file "$HYPRTRIXIE_ROOT/system/hypr/hyprpaper.conf" /etc/xdg/hypr/hyprpaper.conf
}

mako_setup() {
  deploy_file "$HYPRTRIXIE_ROOT/config/mako/defaults" "$SHARE_DIR/mako/defaults" || return 1
  deploy_user_once "$HYPRTRIXIE_ROOT/config/mako/config" .config/mako/config
}

walker_install() {
  local provider
  release_extract walker walker "$BIN_DIR/walker" || return 1
  release_extract elephant elephant-linux-amd64 "$BIN_DIR/elephant" || return 1
  for provider in "${ELEPHANT_PROVIDERS[@]}"; do
    release_extract "elephant-$provider" "$provider-linux-amd64.so" "$ELEPHANT_LIB/$provider.so" 0644 || return 1
  done
  rm -rf /etc/xdg/walker/themes/hyprtrixie
  rm -f "$BIN_DIR/hyprtrixie-power-menu"
  rm -f /etc/xdg/elephant/menus/themes.lua /etc/xdg/elephant/menus/backgrounds.lua
  deploy_file "$HYPRTRIXIE_ROOT/system/walker/config.toml" /etc/xdg/walker/config.toml || return 1
  deploy_tree "$HYPRTRIXIE_ROOT/system/elephant/menus" /etc/xdg/elephant/menus
}

walker_ready() {
  local provider
  commands_present walker elephant || return 1
  for provider in "${ELEPHANT_PROVIDERS[@]}"; do
    [[ -f $ELEPHANT_LIB/$provider.so ]] || return 1
  done
}

