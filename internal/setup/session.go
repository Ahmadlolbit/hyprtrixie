func (context *Context) hyprlandUserReady(*runlog.Log) error {
	return holds(mentions(context.Person.Path(hyprUser), filepath.Join(hyprShare(), "hyprtrixie.lua")))
}

func hyprlandAccepted(lines []string) bool {
	start := slices.IndexFunc(lines, func(line string) bool { return strings.Contains(line, verdictLine) })
	if start < 0 {
		return false
	}
	verdict := slices.IndexFunc(lines[start:], func(line string) bool {
		return !strings.Contains(line, verdictLine) && strings.Trim(line, " \t") != ""
	})
	return verdict >= 0 && lines[start+verdict] == "config ok"
}

func hyprlandComplaint(lines []string) string {
	start := slices.IndexFunc(lines, func(line string) bool { return strings.Contains(line, verdictLine) })
	if start < 0 {
		return ""
	}
	shown := lines[start:]
	return strings.Join(shown[:min(verdictShown, len(shown))], "\n") + "\n"
}

func (context *Context) hyprlandConfigOK(log *runlog.Log) error {
	runtime, err := os.MkdirTemp("", "hyprtrixie")
	if err != nil {
		return err
	}
	defer os.RemoveAll(runtime)
	if err := run.Logged(log, "chown", context.Person.Name+":", runtime); err != nil {
		return err
	}
	var output bytes.Buffer
	context.Person.RunWithin(run.Minute, &output, "env", "XDG_RUNTIME_DIR="+runtime, "Hyprland", "--verify-config")
	lines := strings.Split(strings.TrimRight(output.String(), "\n"), "\n")
	accepted := hyprlandAccepted(lines)
	if !accepted {
		fmt.Fprint(log, hyprlandComplaint(lines))
	}
	return holds(accepted)
}

func (context *Context) hyprlockSetup(*runlog.Log) error {
	clock := "$TIME"
	if context.Config.Get("CLOCK_FORMAT") == "12h" {
		clock = "$TIME12"
	}
	return context.Deploy.File("system/hypr/hyprlock.conf", hyprSystem+"hyprlock.conf", "TIME="+clock)
}

func idleListener(timeout int, action, resume string) string {
	text := fmt.Sprintf("\nlistener {\n    timeout = %d\n    on-timeout = %s\n", timeout, action)
	if resume != "" {
		text += "    on-resume = " + resume + "\n"
	}
	return text + "}\n"
}

func lockListeners(lock int) string {
	var text strings.Builder
	if lock > secondsAMin {
		text.WriteString(idleListener(lock-dimAhead, "brightnessctl -s set 10%", "brightnessctl -r"))
		text.WriteString(idleListener(lock-dimAhead, "brightnessctl -sd '*::kbd_backlight' set 0", "brightnessctl -rd '*::kbd_backlight'"))
	}
	text.WriteString(idleListener(lock, "loginctl lock-session", ""))
	text.WriteString(idleListener(lock+dimAhead, dpmsOff, dpmsOn))
	return text.String()
}

func hypridleConfig(lock, suspend, saver int) string {
	var text strings.Builder
	text.WriteString("general {\n    lock_cmd = pidof hyprlock || hyprlock\n    before_sleep_cmd = loginctl lock-session\n")
	text.WriteString("    after_sleep_cmd = " + dpmsOn + "\n}\n")
	if saver > 0 && (lock == 0 || saver < lock) {
		text.WriteString(idleListener(saver, "hyprtrixie-screensaver start", ""))
	}
	if lock > 0 {
		text.WriteString(lockListeners(lock))
	}
	if suspend > 0 {
		text.WriteString(idleListener(suspend, "systemctl suspend", ""))
	}
	return text.String()
}

func (context *Context) seconds(key string) int {
	minutes, _ := strconv.Atoi(context.Config.Get(key))
	return minutes * secondsAMin
}

func (context *Context) hypridleSetup(*runlog.Log) error {
	text := hypridleConfig(context.seconds("IDLE_LOCK_MINUTES"), context.seconds("IDLE_SUSPEND_MINUTES"), context.seconds("SCREENSAVER_MINUTES"))
	_, err := context.Deploy.Content([]byte(text), hyprSystem+"hypridle.conf")
	return err
}

func (context *Context) makoSetup(log *runlog.Log) error {
	changed, err := context.Deploy.Changed("config/mako/defaults", filepath.Join(env.ShareDir(), "mako/defaults"))
	if err != nil {
		return err
	}
	if err := context.Deploy.UserOnce("config/mako/config", makoUser); err != nil {
		return err
	}
	if changed && context.Person.SessionRunning() {
		context.Person.Run(log, "makoctl", "reload")
	}
	return nil
}

func (context *Context) walkerInstall(log *runlog.Log) error {
	if err := fetch.ReleaseExtract(log, "walker", "walker", filepath.Join(env.BinDir(), "walker"), programMode); err != nil {
		return err
	}
	if err := fetch.ReleaseExtract(log, "elephant", "elephant-linux-amd64", filepath.Join(env.BinDir(), "elephant"), programMode); err != nil {
		return err
	}
	for _, provider := range elephantProviders {
		if err := fetch.ReleaseExtract(log, "elephant-"+provider, provider+"-linux-amd64.so", filepath.Join(elephantLib, provider+".so"), plainMode); err != nil {
			return err
		}
	}
	for _, old := range []string{"/etc/xdg/walker/themes/hyprtrixie", "/etc/xdg/elephant/menus"} {
		if err := os.RemoveAll(old); err != nil {
			return err
		}
	}
	if err := removeFiles(filepath.Join(env.BinDir(), "hyprtrixie-power-menu"), filepath.Join(elephantLib, "menus.so")); err != nil {
		return err
	}
	return context.Deploy.File("system/walker/config.toml", "/etc/xdg/walker/config.toml")
}

func walkerReady(*runlog.Log) error {
	if err := apt.Commands("walker", "elephant"); err != nil {
		return err
	}
	for _, provider := range elephantProviders {
		if err := fileThere(filepath.Join(elephantLib, provider+".so")); err != nil {
			return err
		}
	}
	return nil
}

func (context *Context) commandInstall(*runlog.Log) error {
	if err := os.MkdirAll(env.BinDir(), programMode); err != nil {
		return err
	}
	if err := atomic.Symlink(filepath.Join(env.Root(), "hyprtrixie"), filepath.Join(env.BinDir(), "hyprtrixie")); err != nil {
		return err
	}
	return context.Deploy.Tool("hyprtrixie-core")
}

func commandReady(*runlog.Log) error {
	installed, err := fsutil.RealPath(filepath.Join(env.BinDir(), "hyprtrixie"))
	if err != nil {
		return err
	}
	script, err := fsutil.RealPath(filepath.Join(env.Root(), "hyprtrixie"))
	if err != nil {
		return err
	}
	return expect(installed == script, "it points at "+installed)
}

func (context *Context) tipsInstall(*runlog.Log) error {
	if err := context.Deploy.File("system/tips.txt", filepath.Join(env.ShareDir(), "tips.txt")); err != nil {
		return err
	}
	if err := context.Deploy.Tool("hyprtrixie-tip"); err != nil {
		return err
	}
	settings := context.Config
	return context.Deploy.File("system/tips.conf", "/etc/hyprtrixie/tips", "TERMINAL="+settings.Get("TIPS_TERMINAL"),
		"WELCOME="+settings.Get("TIPS_WELCOME"), "NOTIFY="+settings.Get("TIPS_NOTIFY"))
}

func (context *Context) deployUserUnits(units ...string) error {
	for _, unit := range units {
		if err := context.Deploy.File("system/systemd/"+unit, userUnits+unit); err != nil {
			return err
		}
	}
	return nil
}

func (context *Context) tipTimerInstall(log *runlog.Log) error {
	if err := context.deployUserUnits(tipService, tipTimer); err != nil {
		return err
	}
	return run.Logged(log, "systemctl", "--global", "enable", tipTimer)
}

func (context *Context) careInstall(log *runlog.Log) error {
	if err := context.Deploy.Tool("hyprtrixie-care"); err != nil {
		return err
	}
	if err := context.deployUserUnits(careService, careTimer); err != nil {
		return err
	}
	action := "disable"
	if context.Config.Get("CARE_NOTIFY") == "yes" {
		action = "enable"
	}
	return run.Logged(log, "systemctl", "--global", action, careTimer)
}

func (context *Context) brightnessAccess(log *runlog.Log) error {
	if err := context.Deploy.File("system/udev/90-hyprtrixie-brightness.rules", "/etc/udev/rules.d/90-hyprtrixie-brightness.rules"); err != nil {
		return err
	}
	if err := context.Person.AddGroups(log, "video"); err != nil {
		return err
	}
	run.Logged(log, "udevadm", "control", "--reload")
	return run.Logged(log, "udevadm", "trigger", "--subsystem-match=backlight", "--subsystem-match=leds", "--action=add")
}

func (context *Context) toolStep(title, tool string) {
	context.Run.Step(title, func(*runlog.Log) error { return context.Deploy.Tool(tool) })
}

func timerCheck(timer string) step.Work {
	return func(*runlog.Log) error {
		return expect(fsutil.IsLink(userUnits+"timers.target.wants/"+timer), timer+" isn't enabled")
	}
}

func sessionSteps(context *Context) {
	context.Run.Step("Install session packages", packages("session"))
	context.Run.Step("Install the Hyprland defaults", context.hyprlandDefaults)
	context.toolStep("Install the session starter", "hyprtrixie-start")
	context.Run.Step("Put the hyprtrixie command on the PATH", context.commandInstall)
	context.toolStep("Install the floating terminal", "hyprtrixie-terminal")
	context.toolStep("Install the package picker", "hyprtrixie-pkg")
	context.Run.Step("Install the tips", context.tipsInstall)
	context.Run.Step("Show a tip now and then", context.tipTimerInstall)
	context.Run.Step("Keep the firmware list fresh", func(log *runlog.Log) error { return service.Start(log, fwupdTimer) })
	context.Run.Step("Look after the system quietly", context.careInstall)
	context.Run.Step("Apply display and input settings", context.hyprlandOptions)
	context.Run.Step("Set up your Hyprland config", context.hyprlandUserConfig)
	context.Run.Step("Set up the lock screen", context.hyprlockSetup)
	context.Run.Step("Set up idle locking and suspend", context.hypridleSetup)
	context.Run.Step("Set up the wallpaper", func(*runlog.Log) error {
		return context.Deploy.File("system/hypr/hyprpaper.conf", hyprSystem+"hyprpaper.conf")
	})
	context.Run.Step("Set up notifications", context.makoSetup)
	context.Run.Step("Install the Walker launcher", context.walkerInstall)
	context.Run.Step("Let you change the brightness", context.brightnessAccess)
	context.toolStep("Install the screenshot command", "hyprtrixie-screenshot")
	context.Run.Step("Install the screensaver", func(*runlog.Log) error {
		if err := context.Deploy.Tool("hyprtrixie-screensaver"); err != nil {
			return err
		}
		return context.Deploy.File("system/screensaver.txt", filepath.Join(env.ShareDir(), "screensaver.txt"))
	})
}

func sessionChecks(context *Context) {
	context.Run.Check("Your account can change the brightness", func(*runlog.Log) error {
		return expect(context.Person.InGroup("video"), "you are not in the video group")
	})
	if context.Config.Get("CARE_NOTIFY") == "yes" {
		context.Run.Check("The quiet system checks are scheduled", timerCheck(careTimer))
	}
	context.Run.Check("The hyprtrixie command points at this folder", commandReady)
	context.Run.Check("The firmware list is refreshed", func(*runlog.Log) error {
		return expect(service.Enabled(fwupdTimer), fwupdTimer+" isn't enabled")
	})
	context.Run.Check("Hyprland accepts the configuration", context.hyprlandConfigOK)
	context.Run.Check("Idle locking and suspend are configured", filesCheck(hyprSystem+"hypridle.conf"))
	context.Run.Check("The lock screen is configured", filesCheck(hyprSystem+"hyprlock.conf"))
	context.Run.Check("Notifications are set up", filesCheck(context.Person.Path(makoUser)))
	context.Run.Check("Session packages are installed", func(log *runlog.Log) error { return apt.ListsPresent(log, "session") })
	context.Run.Check("The package picker is installed", commands("hyprtrixie-pkg"))
	context.Run.Check("The screensaver is installed", commands("hyprtrixie-screensaver", "tte"))
	context.Run.Check("The screenshot command is installed", commands("hyprtrixie-screenshot"))
	context.Run.Check("The session starter is installed", commands("hyprtrixie-start"))
	context.Run.Check("The floating terminal is installed", commands("hyprtrixie-terminal"))
	context.Run.Check("Tip notifications are scheduled", timerCheck(tipTimer))
	context.Run.Check("The tips are installed", commands("hyprtrixie-tip"))
	context.Run.Check("Your Hyprland config loads the hyprtrixie defaults", context.hyprlandUserReady)
	context.Run.Check("Walker and its providers are installed", walkerReady)
	context.Run.Check("The wallpaper service is configured", filesCheck(hyprSystem+"hyprpaper.conf"))
}
